async page => {
  const passed = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); passed.push(label); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://localhost:8095');
  await page.getByRole('heading', { name: 'My hikes', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'Friends', exact: true }).click();
  check(await page.getByRole('button', { name: /^View .*reviewed by/ }).count() === 3, 'Feed shows three sample reviews');
  await page.getByRole('button', { name: 'View Mount Tammany, reviewed by Maya Chen', exact: true }).click();
  await page.getByRole('heading', { name: 'Mount Tammany', exact: true }).waitFor();
  check(await page.getByText('Loved it', { exact: true }).isVisible(), 'Friend detail shows enjoyment rating');
  await page.getByRole('button', { name: 'Log this hike', exact: true }).click();
  const dialog = page.getByRole('dialog');
  check(await dialog.getByRole('textbox', { name: 'Hike name', exact: true }).inputValue() === 'Mount Tammany', 'Log this hike prefills trail name');
  check(await dialog.getByRole('button', { name: 'Save', exact: true }).isDisabled(), 'Save disabled until both ratings are set');
  await page.evaluate(() => { window.__prompts = 0; window.confirm = () => { window.__prompts++; return false; }; });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  check(await page.evaluate(() => window.__prompts === 0), 'Untouched prefilled form cancels without warning');
  await page.getByRole('button', { name: 'Log this hike', exact: true }).click();
  await dialog.getByRole('radio', { name: 'Enjoyment: 5 out of 5', exact: true }).click();
  check(await dialog.getByRole('button', { name: 'Save', exact: true }).isDisabled(), 'One rating alone cannot save');
  await dialog.getByRole('radio', { name: 'Difficulty: 3 out of 5', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Hike notes', exact: true }).fill('A great morning on the trail.');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  check(await page.evaluate(() => window.__prompts === 1), 'Edited form requests discard confirmation');
  check(await dialog.getByRole('textbox', { name: 'Hike notes', exact: true }).inputValue() === 'A great morning on the trail.', 'Keep editing preserves notes');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'View Mount Tammany', exact: true }).waitFor();
  check(await page.getByText('1 hike logged', { exact: true }).isVisible(), 'Save returns to personal hike list');
  await page.getByRole('button', { name: 'View Mount Tammany', exact: true }).click();
  check(await page.getByText('Your review', { exact: true }).isVisible(), 'Saved hike opens personal detail');
  check(await page.getByText('A great morning on the trail.', { exact: true }).isVisible(), 'Saved notes appear in details');

  await page.getByRole('button', { name: 'Back to My hikes', exact: true }).click();
  await page.getByRole('button', { name: 'Log a hike', exact: true }).click();
  check(await dialog.getByRole('textbox', { name: 'Hike name', exact: true }).inputValue() === '', 'New log clears previous form');
  await dialog.getByRole('textbox', { name: 'Hike name', exact: true }).fill('   ');
  await dialog.getByRole('radio', { name: 'Enjoyment: 2 out of 5', exact: true }).click();
  await dialog.getByRole('radio', { name: 'Difficulty: 2 out of 5', exact: true }).click();
  check(await dialog.getByRole('button', { name: 'Save', exact: true }).isDisabled(), 'Whitespace hike name cannot save');
  await page.evaluate(() => { window.confirm = () => true; });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  check(await page.getByText('1 hike logged', { exact: true }).isVisible(), 'Discard does not add a hike');
  await page.route('https://images.unsplash.com/**', route => route.abort());
  await page.getByRole('tab', { name: 'Friends', exact: true }).click();
  await page.getByText('Photo unavailable', { exact: true }).first().waitFor();
  check(true, 'Failed photos show a fallback instead of breaking feed');
  await page.getByRole('button', { name: 'View Lake Minnewaska, reviewed by Sam Patel', exact: true }).click();
  await page.getByRole('heading', { name: 'Lake Minnewaska', exact: true }).waitFor();
  await page.getByText('Photo unavailable', { exact: true }).waitFor();
  check(await page.getByText('Fairly easy', { exact: true }).isVisible(), 'Lake review keeps its own difficulty');
  await page.setViewportSize({ width: 320, height: 700 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Details fit a narrow 320px viewport');
  await page.getByRole('button', { name: 'Back to Friends', exact: true }).click();
  await page.getByRole('tab', { name: 'Friends', exact: true }).waitFor();
  check(await page.getByRole('button', { name: /^View .*reviewed by/ }).count() === 3, 'Back returns to Friends');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.unroute('https://images.unsplash.com/**');
  await page.getByRole('tab', { name: 'My hikes', exact: true }).click();
  await page.getByRole('tab', { name: 'Friends', exact: true }).click();

  check(errors.length === 0, 'No uncaught JavaScript errors');
  return { passed: passed.length, checks: passed, errors };
}
